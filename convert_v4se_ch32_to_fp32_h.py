#!/usr/bin/env python3
"""
Convert TCN+SE ch=32 FP32 PyTorch model -> C header for H743 deployment.
Folds BN into conv weights and biases (training-time optimization).
Output: 13 FP32 conv tensors + 17 FP32 bias tensors (matches existing model_v4_se_23dim_ch32_hybrid_s42.h layout).
"""
import torch
import numpy as np
import struct

PT_PATH = 'model_v4_se_23dim_b64_ch32_do01_window16_s42.pt'
OUT_H   = 'h743/Core/Inc/model_v4_se_23dim_ch32_fp32_s42.h'

sd = torch.load(PT_PATH, map_location='cpu')['state_dict']

def fold_bn(w, b, mean, var, gamma, beta, eps=1e-5):
    """Fold BatchNorm into conv weight+bias for inference.
    w: [out_ch, in_ch, K] (conv weight)
    b: [out_ch] (conv bias)
    Returns: (w_folded, b_folded)
    """
    scale = gamma / torch.sqrt(var + eps)  # [out_ch]
    w_folded = w * scale.view(-1, 1, 1)
    b_folded = (b - mean) * scale + beta
    return w_folded, b_folded

# 13 conv tensors (matches hybrid .h naming)
# tcn.0 has 3 conv (conv1, conv2, residual) + 2 BN
# tcn.1, tcn.2 have 2 conv each (conv1, conv2) + 2 BN
# total: 3 + 2 + 2 = 7 conv layers, but we treat residual as 1x1 conv

# tcn.0: conv1, conv2, residual + BN1, BN2 (no BN for residual)
# tcn.1: conv1, conv2 + BN1, BN2
# tcn.2: conv1, conv2 + BN1, BN2

# Total outputs in C header (same as hybrid):
# - 7 FP32 weights (folded): tcn.{0,1,2}.{conv1,conv2} + tcn.0.residual
# - 7 bias (after fold): 6 conv (2+2+2) + 1 residual
# - 3 SE.fc1.weight, 3 SE.fc1.bias
# - 3 SE.fc2.weight, 3 SE.fc2.bias
# - fc1.weight, fc1.bias
# - fc2.weight, fc2.bias
# Total: 7 weights + 7 conv biases + 3 fc1 + 3 fc2 + 1 fc1 + 1 fc1 bias + 1 fc2 + 1 fc2 bias = wait

# Let me list correctly per hybrid .h:
# 7 weight tensors (w_tcn_X_conv{1,2}_weight + w_tcn_0_residual_weight): 7 entries
# 7 bias tensors (b_tcn_X_conv{1,2}_bias + b_tcn_0_residual_bias): 7 entries
# 3 SE fc1 weight (FP32 in hybrid): 3
# 3 SE fc1 bias: 3
# 3 SE fc2 weight (FP32 in hybrid): 3
# 3 SE fc2 bias: 3
# 1 fc1 weight (FP32 in hybrid): 1
# 1 fc1 bias: 1
# 1 fc2 weight (FP32 in hybrid): 1
# 1 fc2 bias: 1
# TOTAL: 7+7+3+3+3+3+1+1+1+1 = 30 tensors
# (hybrid has 13 int8 + 13 scale + 2 head fp32 + 17 bias = 45 entries, we have 30 here)

# We need to fold BN into conv, then write as FP32 arrays.
# For residual, no BN - just use raw weight + bias.

tensors_to_write = {}

# Process 3 blocks
for blk in [0, 1, 2]:
    for cn in ['conv1', 'conv2']:
        w = sd[f'tcn.{blk}.{cn}.weight']
        b = sd[f'tcn.{blk}.{cn}.bias']
        bn_w = sd[f'tcn.{blk}.bn1.weight' if cn=='conv1' else f'tcn.{blk}.bn2.weight']
        bn_b = sd[f'tcn.{blk}.bn1.bias' if cn=='conv1' else f'tcn.{blk}.bn2.bias']
        bn_m = sd[f'tcn.{blk}.bn1.running_mean' if cn=='conv1' else f'tcn.{blk}.bn2.running_mean']
        bn_v = sd[f'tcn.{blk}.bn1.running_var' if cn=='conv1' else f'tcn.{blk}.bn2.running_var']
        w_f, b_f = fold_bn(w, b, bn_m, bn_v, bn_w, bn_b)
        tensors_to_write[f'w_tcn_{blk}_{cn}_weight'] = w_f
        tensors_to_write[f'b_tcn_{blk}_{cn}_bias']   = b_f

# Block 0 residual: no BN
tensors_to_write['w_tcn_0_residual_weight'] = sd['tcn.0.residual.weight']
tensors_to_write['b_tcn_0_residual_bias']   = sd['tcn.0.residual.bias']

# SE blocks (no BN, just linear)
for blk in [0, 1, 2]:
    tensors_to_write[f'w_tcn_{blk}_se_fc1_weight'] = sd[f'tcn.{blk}.se.fc1.weight']
    tensors_to_write[f'b_tcn_{blk}_se_fc1_bias']   = sd[f'tcn.{blk}.se.fc1.bias']
    tensors_to_write[f'w_tcn_{blk}_se_fc2_weight'] = sd[f'tcn.{blk}.se.fc2.weight']
    tensors_to_write[f'b_tcn_{blk}_se_fc2_bias']   = sd[f'tcn.{blk}.se.fc2.bias']

# Head (no BN, just linear)
tensors_to_write['fc1_weight'] = sd['fc1.weight']
tensors_to_write['b_fc1_bias']   = sd['fc1.bias']
tensors_to_write['fc2_weight'] = sd['fc2.weight']
tensors_to_write['b_fc2_bias']   = sd['fc2.bias']

# Write C header
total_params = sum(t.numel() for t in tensors_to_write.values())
header = f"""/* Auto-generated by convert_v4se_ch32_to_fp32_h.py
 * TCN+SE ch=32 (23-dim SCADA, dropout=0.1) - FULL FP32 (no quantization, no T scaling needed)
 * seed=42 - BN folded into conv weights/biases at export time
 * Source: {PT_PATH}
 */
#ifndef TCN_V4_SE_23DIM_CH32_FP32_S42_WEIGHTS_H
#define TCN_V4_SE_23DIM_CH32_FP32_S42_WEIGHTS_H
#include <stdint.h>
#define TCN_V4_SE_23DIM_CH32_N_TENSORS    30
#define TCN_V4_SE_23DIM_CH32_TOTAL_PARAMS  {total_params}
#ifdef __cplusplus
extern "C" {{
#endif

"""

body = ""
for name, tensor in tensors_to_write.items():
    shape = tuple(tensor.shape)
    n = tensor.numel()
    arr = tensor.contiguous().flatten().numpy()
    body += f"/* {name}  shape={shape}  numel={n}  (FP32, BN-folded) */\n"
    body += f"static const float v4se23_ch32_s42_{name}[{n}] = {{\n"
    # Write 8 floats per line
    for i in range(0, n, 8):
        chunk = arr[i:i+8]
        body += "  " + ", ".join(f"{x:.7e}f" for x in chunk) + ",\n"
    body += "};\n\n"

footer = """#ifdef __cplusplus
}
#endif
#endif /* TCN_V4_SE_23DIM_CH32_FP32_S42_WEIGHTS_H */
"""

with open(OUT_H, 'w') as f:
    f.write(header + body + footer)

print(f"Wrote {OUT_H}")
print(f"Total params: {total_params}")
print(f"File size: {sum(t.numel()*4 for t in tensors_to_write.values())} bytes ({sum(t.numel()*4 for t in tensors_to_write.values())/1024:.1f} KB)")
