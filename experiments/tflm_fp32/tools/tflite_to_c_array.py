#!/usr/bin/env python3
"""
.tflite -> C 数组头文件 (给 MCU 的 TFLM 解释器用).

要点 (来自历史踩坑):
  * **纯 ASCII** 输出 + 正确闭合的注释. 之前 scaler_export.h 因为 GBK 编码把
    `*/` 吞掉, 整份头文件被编译器当成注释 -> 一堆 undeclared identifier.
  * 8 字节对齐 (flatbuffer 里要读 float32, 对齐不对会踩 unaligned access).
  * 放 Flash (const), 不占 RAM.
  * 长度宏必须跟数组实际长度一致, 且**编译期断言** (C11 _Static_assert;
    AC6 用 C99+ 时也能过), 防止手改数组忘了改宏.

用法:
    python experiments/tflm_fp32/tools/tflite_to_c_array.py \
        --tflite experiments/tflm_fp32/artifacts/model_tflm_fp32_s42.tflite \
        --out    MCU/Core/Inc/model_tflm_fp32_s42_data.h
"""
from __future__ import annotations

import argparse
import hashlib
import os
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

# 16 字节一行, 16 进制字节
BYTES_PER_LINE = 16


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tflite",
                    default="experiments/tflm_fp32/artifacts/model_tflm_fp32_s42.tflite")
    ap.add_argument("--out-header", default="MCU/Core/Inc/model_tflm_fp32_s42_data.h")
    ap.add_argument("--out-source", default="MCU/Core/Src/model_tflm_fp32_s42_data.c")
    ap.add_argument("--symbol", default="g_tflm_model_s42")
    args = ap.parse_args()

    blob = open(args.tflite, "rb").read()
    sha = hashlib.sha256(blob).hexdigest()
    n = len(blob)

    # ---- 头文件: 只有**声明** (extern) ----
    # 为什么拆两个文件: C++ 里 namespace scope 的 `const` 变量默认是**内部链接**,
    # 头文件里写定义 -> 每个 include 它的 TU 都各拷一份 85KB.
    # 头文件写 extern 声明 + .c 文件写定义 -> 全工程只有一份, 且 C/C++ 都能用.
    hdr = []
    a = hdr.append
    a("/* Auto-generated by experiments/tflm_fp32/tools/tflite_to_c_array.py")
    a(" * TFLite Micro flatbuffer (FP32, no quantization) -> C array for STM32H743")
    a(" *")
    a(" * Source   : %s" % os.path.basename(args.tflite))
    a(" * SHA256   : %s" % sha)
    a(" * Bytes    : %d" % n)
    a(" *")
    a(" * DO NOT EDIT BY HAND. Regenerate with:")
    a(" *   python experiments/tflm_fp32/tools/tflite_to_c_array.py")
    a(" *")
    a(" * The array itself lives in model_tflm_fp32_s42_data.c (one copy only).")
    a(" * This header only declares it, so C++ TUs do not duplicate 85KB.")
    a(" */")
    a("#ifndef MODEL_TFLM_FP32_S42_DATA_H")
    a("#define MODEL_TFLM_FP32_S42_DATA_H")
    a("")
    a("#include <stdint.h>")
    a("")
    a("#define TFLM_MODEL_S42_BYTES  %d" % n)
    a("#define TFLM_MODEL_S42_SHA256 \"%s\"" % sha)
    a("")
    a("#ifdef __cplusplus")
    a('extern "C" {')
    a("#endif")
    a("")
    a("extern const unsigned char %s[TFLM_MODEL_S42_BYTES];" % args.symbol)
    a("")
    a("#ifdef __cplusplus")
    a("}")
    a("#endif")
    a("")
    a("#endif /* MODEL_TFLM_FP32_S42_DATA_H */")

    # ---- 源文件: 定义 ----
    src = []
    a = src.append
    a("/* Auto-generated by experiments/tflm_fp32/tools/tflite_to_c_array.py")
    a(" * Do not edit by hand.")
    a(" *")
    a(" * The flatbuffer is stored contiguously, byte for byte, exactly as produced by")
    a(" * the TFLite converter (sha256 %s)." % sha)
    a(" *")
    a(" * 8-byte aligned: the flatbuffer root table and the float32 weight buffers")
    a(" * inside it are accessed as 4-byte words; 8-byte alignment keeps the")
    a(" * Cortex-M7 happy and lets the array be placed in Flash verbatim.")
    a(" */")
    a("")
    a('#include "model_tflm_fp32_s42_data.h"')
    a("")
    a("__attribute__((aligned(8)))")
    a("const unsigned char %s[TFLM_MODEL_S42_BYTES] = {" % args.symbol)
    for i in range(0, n, BYTES_PER_LINE):
        chunk = blob[i:i + BYTES_PER_LINE]
        a("  " + " ".join("0x%02x," % b for b in chunk))
    a("};")
    a("")
    a("/* Compile-time check: the length macro must match the array. */")
    a("#if defined(__STDC_VERSION__) && __STDC_VERSION__ >= 201112L")
    a("_Static_assert(sizeof(%s) == TFLM_MODEL_S42_BYTES,"
      " \"TFLM model array size mismatch\");" % args.symbol)
    a("#endif")

    for path, lines in ((args.out_header, hdr), (args.out_source, src)):
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w", encoding="ascii", newline="\n") as f:
            f.write("\n".join(lines) + "\n")

    # 自检: 回读 + 逐字节比对 (源绑定: 别信"写出来了", 回读验证)
    txt = open(args.out_source, "r", encoding="ascii").read()
    assert "*/" in txt and txt.count("/*") >= 2
    body = txt.split("= {", 1)[1].split("};", 1)[0]
    got = bytes(int(tok, 16) for tok in body.replace(",", " ").split())
    if got != blob:
        print("SELF-CHECK FAILED: 回读字节与源文件不一致 (%d vs %d)"
              % (len(got), len(blob)))
        return 1

    print("wrote %s" % args.out_header)
    print("wrote %s  (%d bytes, sha256 %s)" % (args.out_source, n, sha[:16]))
    print("self-check OK: 回读 %d 字节逐字节一致" % len(got))
    return 0


if __name__ == "__main__":
    sys.exit(main())
