#!/usr/bin/env python3
"""
gen_int16_weights.py -- 从 **FP32 部署真值头** 生成 Hybrid-INT16 权重头.

为什么是 INT16 而不是 INT8
--------------------------
  PC 侧 2x2 归因 (compare_fp32_vs_hybrid.py) 证明: 全量 INT8 / Hybrid-INT8 把 FPR
  从 5.91% 推到 6.89%/6.98%, 根因是 **权重量化误差** 系统性把 logit 上推.
  Hybrid-INT16 (scale = absmax/32767) 的量化误差比 INT8 小 256 倍:
      部署区 F1 0.8671 / FPR 0.0591 / P 0.9361 / R 0.8075
      跟 FP32 **逐窗 0 决策翻转**, 每个阈值都完全一致.
  => INT16 是 "无损 hybrid": 拿到 INT8 的资源, 保住 FP32 的精度.

源绑定
------
  输入 = MCU/Core/Inc/model_v4_se_23dim_ch32_fp32_s42.h (Route E 部署真值, 跟 .pt 同源)
  输出 = MCU/Core/Inc/model_v4_se_23dim_ch32_int16_s42.h (要烧进 MCU 的那份)
  ⇒ PC 侧的仿真读的就是这份头, 测的就是要烧的东西 (memory: feedback-parity-test...)

量化方案
--------
  per-output-channel 对称 int16:
      scale[oc] = absmax(oc) / 32767
      q[oc]     = clip(round(w[oc] / scale[oc]), -32768, 32767)
  13 个 conv/SE 张量量化; 分类器 fc1/fc2 (1056 参数, 太小) 与全部 bias 保持 FP32.

用法: python gen_int16_weights.py
"""
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from sim_hybrid_kernel import _SHAPES, _TENSORS

FP32_HDR = os.path.join(HERE, "MCU/Core/Inc/model_v4_se_23dim_ch32_fp32_s42.h")
OUT_HDR = os.path.join(HERE, "MCU/Core/Inc/model_v4_se_23dim_ch32_int16_s42.h")
SEED = 42
PFX = "v4se23_ch32_s%d_" % SEED        # 输入头 (FP32 部署真值) 的前缀
OUT_PFX = "v4se23_ch32_i16_s%d_" % SEED  # 输出头的前缀: **必须跟 FP32/int8 头区分**
#   (int8 头用 v4se23_ch32_i8_, FP32 头和 hybrid-int8 头都用 v4se23_ch32_s42_;
#    三个头同前缀同名字不同类型 -> 同一个 TU 里 include 两个就是 redefinition 编译错)

QMAX = 32767
QMIN = -32768


# ---------------------------------------------------------------------------
# header 解析 (跟 sim_hybrid_kernel.parse_header 同口径)
# ---------------------------------------------------------------------------

def parse_header(path):
    txt = open(path, encoding="utf-8", errors="replace").read()
    out = {}
    for m in re.finditer(r"static const\s+(\w+)\s+(\w+)\s*\[\s*(\d+)\s*\]\s*=\s*\{(.*?)\};", txt, re.S):
        ctype, name, n, body = m.group(1), m.group(2), m.group(3), m.group(4)
        if ctype == "int8_t":
            vals = np.array([int(x) for x in re.findall(r"-?\d+", body)], dtype=np.int8)
        elif ctype == "int16_t":
            vals = np.array([int(x) for x in re.findall(r"-?\d+", body)], dtype=np.int16)
        elif ctype == "int32_t":
            vals = np.array([int(x) for x in re.findall(r"-?\d+", body)], dtype=np.int32)
        else:
            vals = np.array([float(x[:-1]) for x in re.findall(r"[-+0-9.eE]+f", body)], dtype=np.float32)
        assert len(vals) == int(n), (name, len(vals), int(n))
        out[name] = vals
    return out


def quantize_per_channel_int16(w, shape):
    """(out_ch, ...) -> (int16 flat array, float32 per-channel scale)."""
    O = shape[0]
    flat = np.asarray(w, dtype=np.float32).reshape(O, -1)
    absmax = np.max(np.abs(flat.astype(np.float64)), axis=1)
    absmax = np.maximum(absmax, 1e-12)
    scale = (absmax / QMAX).astype(np.float32)
    q = np.clip(np.round(flat.astype(np.float64) / scale.astype(np.float64)[:, None]),
                QMIN, QMAX).astype(np.int16)
    return q.reshape(-1), scale


def gen_int16_literal(name, arr, per_line=10):
    flat = arr.flatten()
    n = flat.size
    lines = ["static const int16_t %s[%d] = {" % (name, n)]
    row = []
    for i, v in enumerate(flat):
        row.append("%7d" % int(v))
        if (i + 1) % per_line == 0 or i == n - 1:
            lines.append("    " + ", ".join(row) + ("," if i != n - 1 else ""))
            row = []
    lines.append("};")
    return "\n".join(lines)


def gen_float_literal(name, arr, per_line=6):
    flat = arr.flatten()
    n = flat.size
    lines = ["static const float %s[%d] = {" % (name, n)]
    row = []
    for i, v in enumerate(flat):
        row.append("%.7ef" % float(v))
        if (i + 1) % per_line == 0 or i == n - 1:
            lines.append("    " + ", ".join(row) + ("," if i != n - 1 else ""))
            row = []
    lines.append("};")
    return "\n".join(lines)


def main():
    raw = parse_header(FP32_HDR)
    print("[源] %s" % os.path.basename(FP32_HDR))
    print("[出] %s" % os.path.basename(OUT_HDR))

    L = []
    L.append("/* Auto-generated by gen_int16_weights.py")
    L.append(" * TCN+SE ch=32 (23-dim SCADA, dropout=0.1) - Hybrid INT16-weights / FP32-activations")
    L.append(" * seed=%d - 源: model_v4_se_23dim_ch32_fp32_s42.h (Route E 部署真值, BN 已折叠)" % SEED)
    L.append(" *")
    L.append(" * 方案: per-output-channel 对称 int16, scale = absmax/32767")
    L.append(" *       13 个 conv/SE 张量量化; fc1/fc2 与全部 bias 保持 FP32")
    L.append(" *       运行期按需 dequant: w = (float)q * scale[oc]  (不拷 RAM)")
    L.append(" *")
    L.append(" * PC 侧结论 (exp_hybrid_conclusion.py): 部署区 F1 0.8671 / FPR 0.0591")
    L.append(" *   跟 FP32 逐窗 0 决策翻转 (每个阈值都一致) => 无损 hybrid")
    L.append(" */")
    L.append("#ifndef TCN_V4_SE_23DIM_CH32_INT16_S%d_WEIGHTS_H" % SEED)
    L.append("#define TCN_V4_SE_23DIM_CH32_INT16_S%d_WEIGHTS_H" % SEED)
    L.append("#include <stdint.h>")
    L.append("#define TCN_V4_SE_23DIM_CH32_N_QUANT_TENSORS %d" % len(_TENSORS))
    L.append("#define TCN_V4_SE_23DIM_CH32_TOTAL_PARAMS    %d" % sum(int(np.prod(s)) for s in _SHAPES.values()))
    L.append("#ifdef __cplusplus")
    L.append('extern "C" {')
    L.append("#endif")
    L.append("")

    n_q = 0
    max_rel = 0.0
    report = []
    for nm in _TENSORS:
        shp = _SHAPES[nm]
        w = raw[PFX + "w_" + nm + "_weight"].reshape(shp)
        q, sc = quantize_per_channel_int16(w, shp)
        # 量化误差
        dq = (q.astype(np.float32).reshape(shp) * sc.reshape(-1, *([1] * (len(shp) - 1))))
        rel = float(np.abs(dq - w).max() / (np.abs(w).max() + 1e-12))
        max_rel = max(max_rel, rel)
        report.append((nm, shp, q.size, rel))
        n_q += q.size
        L.append("/* w_%s_weight  shape=%s  numel=%d  (INT16 per-channel, scale=absmax/%d) */"
                 % (nm, "x".join(str(s) for s in shp), q.size, QMAX))
        L.append(gen_int16_literal(OUT_PFX + "w_" + nm + "_weight", q))
        L.append("/* w_%s_weight scale per output channel (%d floats) */" % (nm, len(sc)))
        L.append(gen_float_literal(OUT_PFX + "s_" + nm + "_weight", sc))
        L.append("")

    # FP32: fc1 / fc2 权重 + 全部 bias (逐字复制)
    L.append("/* ---- 以下保持 FP32 (分类器太小 + bias 不量化) ---- */")
    L.append("")
    for nm in ("fc1_weight", "fc2_weight"):
        a = raw[PFX + nm]
        L.append("/* %s  numel=%d  (FP32) */" % (nm, a.size))
        L.append(gen_float_literal(OUT_PFX + nm, a))
        L.append("")
    for nm in _TENSORS:
        a = raw[PFX + "b_" + nm + "_bias"]
        L.append("/* b_%s_bias  numel=%d  (FP32) */" % (nm, a.size))
        L.append(gen_float_literal(OUT_PFX + "b_" + nm + "_bias", a))
        L.append("")
    for nm in ("b_fc1_bias", "b_fc2_bias"):
        a = raw[PFX + nm]
        L.append("/* %s  numel=%d  (FP32) */" % (nm, a.size))
        L.append(gen_float_literal(OUT_PFX + nm, a))
        L.append("")

    L.append("#ifdef __cplusplus")
    L.append("}")
    L.append("#endif")
    L.append("#endif")

    with open(OUT_HDR, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")

    # ---- 汇总 ----
    print("\n%-18s %-14s %8s %12s" % ("张量", "shape", "参数", "最大相对误差"))
    for nm, shp, n, rel in report:
        print("%-18s %-14s %8d %12.3e" % (nm, "x".join(str(s) for s in shp), n, rel))
    print("\n量化张量参数合计: %d (int16 = %d B)" % (n_q, n_q * 2))
    print("最大相对误差: %.3e  (int16 理论上限 1/65534 = %.3e)"
          % (max_rel, 1 / 65534))
    print("输出头大小: %d B (%.1f KB)" % (os.path.getsize(OUT_HDR), os.path.getsize(OUT_HDR) / 1024))

    # ---- 自检: 重新解析刚写的头, 确认可读且 dequant 一致 ----
    raw2 = parse_header(OUT_HDR)
    ok = True
    for nm, shp, n, rel in report:
        q = raw2[OUT_PFX + "w_" + nm + "_weight"]
        sc = raw2[OUT_PFX + "s_" + nm + "_weight"]
        assert len(q) == n and len(sc) == shp[0], nm
        dq = (q.astype(np.float32).reshape(shp) * sc.reshape(-1, *([1] * (len(shp) - 1))))
        w = raw[PFX + "w_" + nm + "_weight"].reshape(shp)
        r = float(np.abs(dq - w).max() / (np.abs(w).max() + 1e-12))
        if r > 1e-4:
            ok = False
            print("  [FAIL] %s 相对误差 %.3e" % (nm, r))
    print("[自检] 回读新头并 dequant: %s" % ("PASS ✅" if ok else "FAIL ❌"))


if __name__ == "__main__":
    main()
